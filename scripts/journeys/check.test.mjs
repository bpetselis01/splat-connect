  const files = ['page.tsx', 'dashboard/toys/[id]/page.tsx', 'learn/(course)/handover/page.tsx', 'api/foo/route.ts', 'layout.tsx', 'loading.tsx', 'not-found.tsx', 'dashboard/layout.tsx'].map((f) => `packages/web/app/${f}`)
