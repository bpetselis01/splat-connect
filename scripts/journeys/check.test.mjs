const row = (platform, route, id = 'A01') => ({ id, platform, route })

test('routeTripwire passes when every route has a row or an opt-out', () => {
  const routes = { web: ['/foo', '/design-system'], mobile: ['index'] }
  assert.deepEqual(routeTripwire([row('web', '/foo'), row('mobile', 'index', 'A02')], routes, { 'web /design-system': 'gallery' }), [])
  assert.deepEqual(routeTripwire([], { web: [], mobile: [] }, {}), [])
})

test('routeTripwire names a route with no row and no opt-out', () => {
  assert.deepEqual(routeTripwire([], { web: ['/foo'], mobile: [] }, {}), ['no journey row: web /foo'])
})

test('routeTripwire does not let a mobile row satisfy a web route of the same text', () => {
  assert.deepEqual(routeTripwire([row('mobile', '/foo')], { web: ['/foo'], mobile: [] }, {}), ['no journey row: web /foo', 'A01: route "/foo" matches no file'])
})

test('routeTripwire rejects a TODO placeholder reason', () => {
  assert.deepEqual(routeTripwire([], { web: ['/foo'], mobile: [] }, { 'web /foo': 'TODO: decide' }), ['routes-without-journeys.json: web /foo is a placeholder, give a real reason or add rows'])
})

test('routeTripwire flags an opt-out whose route is gone or now has a row', () => {
  assert.deepEqual(routeTripwire([], { web: [], mobile: [] }, { 'web /gone': 'x' }), ['stale opt-out, delete it: web /gone does not exist'])
  assert.deepEqual(routeTripwire([row('web', '/foo')], { web: ['/foo'], mobile: [] }, { 'web /foo': 'x' }), ['stale opt-out, delete it: web /foo has rows'])
})

test('routeTripwire flags a row whose route matches no file', () => {
  assert.deepEqual(routeTripwire([row('web', '/typo')], { web: [], mobile: [] }, {}), ['A01: route "/typo" matches no file'])
})

test('routeTripwire flags unsorted opt-out keys and empty reasons', () => {
  const routes = { web: ['/a', '/b'], mobile: [] }
  assert.deepEqual(routeTripwire([], routes, { 'web /b': 'x', 'web /a': 'x' }), ['routes-without-journeys.json: web /a is out of order'])
  assert.deepEqual(routeTripwire([], { web: ['/a'], mobile: [] }, { 'web /a': ' ' }), ['routes-without-journeys.json: web /a needs a reason'])
})

const SRC = {
  'packages/api/src/app.ts': "import admin from './routes/admin.js'\nimport parts from './routes/parts.js'\napp.route('/api/admin', admin)\napp.route('/api/tutorials', parts)",
  'packages/api/src/routes/admin.ts': "admin.get('/tutorials', h)\nadmin.patch('/ideas/:id/status', h)",
  'packages/api/src/routes/parts.ts': "export default subResourceRoutes({ path: 'parts' })",
  'packages/api/src/routes/sub-resource.ts': 'router.post(`/:id/${opts.path}`, h)',
}
const readSrc = (file) => SRC[file] ?? null
const withApi = (...api) => [{ id: 'Q99', api }]

test('apiPathsExist accepts a mounted route, a sub-resource route, a renamed param and Supabase entries', () => {
  assert.deepEqual(apiPathsExist(withApi('GET /api/admin/tutorials?status=pending', 'PATCH /api/admin/ideas/:ideaId/status', 'POST /api/tutorials/:id/parts', 'Supabase auth', 'POST …/accept'), readSrc), [])
})

test('apiPathsExist names a path that no route serves, with its row', () => {
  assert.deepEqual(apiPathsExist(withApi('GET /api/recycling/credit', 'PATCH /api/admin/ideas/:id/state'), readSrc), [
    'Q99: api path /api/recycling/credit matches no route in packages/api/src/routes',
    'Q99: api path /api/admin/ideas/:id/state matches no route in packages/api/src/routes',
  ])
})
