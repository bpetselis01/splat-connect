  const files = ['(tabs)/home/index.tsx', '_layout.tsx', '+not-found.tsx', '+html.tsx', 'util.ts', '_private/screen.tsx', 'toys/[id].tsx', 'toys/[id]/index.tsx', 'index.tsx', '(my)/_layout.tsx'].map((f) => `packages/mobile/app/${f}`)
